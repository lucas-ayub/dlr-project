"""
Numbers and pgfplots tables of the report, from the outputs of the sweeps (not versioned).

    python make_data.py [RESULTS_ROOT]      # default: ~/DLR/dlr-project_resultados

Reads   sata1d_code/joint_cases/sweep_joint_all/all_numbers.json   (1-D joint, sweep_joint_all.py)
        results/sata2d/sweep_joint2d_all/all_numbers.json          (2-D joint, run_sweep_joint2d_all.py)
        sata1d_code/joint_cases/audit_dem/all_numbers.json         (all methods with a DEM only, audit_dem.py)
Writes  ../data/*.dat and ../numbers.tex
"""
import json
import os
import sys

import numpy as np

U = os.path.join(os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/DLR/dlr-project_resultados"), "")
HERE = os.path.dirname(os.path.abspath(__file__))
O = os.path.join(HERE, "..", "data", "")
d1=json.load(open(U+"sata1d_code/joint_cases/sweep_joint_all/all_numbers.json"))
d2=json.load(open(U+"results/sata2d/sweep_joint2d_all/all_numbers.json"))
da=json.load(open(U+"sata1d_code/joint_cases/audit_dem/all_numbers.json"))
da=[r for r in da if r.get("group")!="control"]
print("audit runs", len(da))
def med(x): return float(np.median(x))
macros={}
# 1D sweep
for tag,d,jk,tol in (("One",d1,"joint_line",10),("Two",d2,"joint",3)):
    ref=np.array([r["ref"] for r in d]); no=np.array([r["none"] for r in d]); jo=np.array([r[jk] for r in d])
    nrx=np.array([r["nrx"] for r in d])
    macros[f"Sweep{tag}Runs"]=len(d); macros[f"Sweep{tag}Scenes"]=len({r["scene"] for r in d})
    macros[f"Sweep{tag}MedRef"]=f"{med(ref):.1f}"; macros[f"Sweep{tag}MedNone"]=f"{med(no):.1f}"; macros[f"Sweep{tag}MedJoint"]=f"{med(jo):.1f}"
    unres=((jo>-30)&(jo-ref>10)).sum(); macros[f"Sweep{tag}Unresolved"]=int(unres)
    macros[f"Sweep{tag}WithinTen"]=f"{100*np.mean(jo-ref<=10):.0f}"
    macros[f"Sweep{tag}WithinThree"]=f"{100*np.mean(jo-ref<=3):.0f}"
    macros[f"Sweep{tag}MedGain"]=f"{med(no-jo):.1f}"
    with open(O+f"sweep{tag.lower()}_nrx.dat","w") as f:
        f.write("nrx n medref mednone medjoint medgap within3 within10\n")
        for n in sorted(set(nrx)):
            m=nrx==n
            f.write(f"{n} {m.sum()} {med(ref[m]):.2f} {med(no[m]):.2f} {med(jo[m]):.2f} {med(jo[m]-ref[m]):.2f} {100*np.mean(jo[m]-ref[m]<=3):.1f} {100*np.mean(jo[m]-ref[m]<=10):.1f}\n")
    with open(O+f"sweep{tag.lower()}_scatter.dat","w") as f:
        f.write("none joint ref nrx\n")
        for a,b,c,n in zip(no,jo,ref,nrx): f.write(f"{a:.2f} {b:.2f} {c:.2f} {n}\n")
    print(tag, open(O+f"sweep{tag.lower()}_nrx.dat").read())
# audit
meth=[("none","No SATA"),("whole","SATA whole band"),("sub","SATA per sub-band"),("joint_occ","Joint (sub-apertures)"),("joint_line","Joint (whole line)")]
ref=np.array([r["ref"] for r in da])
with open(O+"audit_methods.dat","w") as f:
    f.write("idx median within10 label\n")
    for i,(k,l) in enumerate(meth):
        v=np.array([r[k] for r in da])
        f.write(f"{i} {med(v):.2f} {100*np.mean(v-ref<=10):.1f} {{{l}}}\n")
print(open(O+"audit_methods.dat").read())
macros["AuditRuns"]=len(da); macros["AuditScenes"]=len({r["scene"] for r in da})
macros["AuditMedRef"]=f"{med(ref):.1f}"
t={k:np.array([r["seconds"][k] for r in da]) for k in ("whole","joint_line")}
macros["AuditTimeWhole"]=f"{med(t['whole']):.2f}"; macros["AuditTimeLine"]=f"{med(t['joint_line']):.1f}"
wl=np.array([r["whole"] for r in da]); jl=np.array([r["joint_line"] for r in da]); sb=np.array([r["sub"] for r in da])
macros["AuditLineBetterWhole"]=f"{med(wl-jl):.1f}"; macros["AuditLineBetterSub"]=f"{med(sb-jl):.1f}"
# SATA (DEM only) against the joint reconstruction over the whole line, every run of the audit
with open(O + "audit_scatter.dat", "w") as f:
    f.write("ref none whole sub occ line nrx\n")
    for r in da:
        f.write(f"{r['ref']:.2f} {r['none']:.2f} {r['whole']:.2f} {r['sub']:.2f} {r['joint_occ']:.2f} {r['joint_line']:.2f} {r['nrx']}\n")
# level left by SATA predicted from the geometry and the DEM against the simulation (nota_joint_vs_sata/prev_sata.py)
pp = os.path.join(U, "sata1d_code/joint_cases/nota_joint_vs_sata/prev_sata.json")
if os.path.exists(pp):
    pv = json.load(open(pp))
    with open(O + "sata_prediction.dat", "w") as f:
        f.write("pwhole swhole psub ssub nrx\n")
        for k, r in pv.items():
            f.write(f"{r['whole']:.2f} {r['sim_whole']:.2f} {r['sub']:.2f} {r['sim_sub']:.2f} {r['nrx']}\n")
    e1 = np.array([r["whole"] - r["sim_whole"] for r in pv.values()]); e2 = np.array([r["sub"] - r["sim_sub"] for r in pv.values()])
    macros["PredRmsWhole"] = f"{np.sqrt(np.mean(e1 ** 2)):.1f}"; macros["PredRmsSub"] = f"{np.sqrt(np.mean(e2 ** 2)):.1f}"
    macros["PredRuns"] = len(pv)
with open(os.path.join(HERE, "..", "numbers.tex"), "w") as f:
    f.write("% generated by report/scripts/make_data.py from the sweep outputs\n")
    for k,v in macros.items(): f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
print(macros)
